/** عدد حقول الرغبات المطلوبة: بحد أقصى 3 وحسب الأقسام المتاحة للفرع */
export function requiredPreferenceCount(branch: string): number {
  return Math.min(3, getAvailableDepartmentsForBranch(branch).length);
}

export function validateDepartmentPreferences(
  preferences: { first?: string; second?: string; third?: string } | null | undefined,
  branch: string
): { ok: true; prefs: DepartmentPreferences } | { ok: false; error: string } {
  const required = requiredPreferenceCount(branch);
  if (required <= 0) {
    return { ok: false, error: 'لا توجد أقسام متاحة لهذا الفرع' };
  }

  const selected = [
    String(preferences?.first || '').trim(),
    String(preferences?.second || '').trim(),
    String(preferences?.third || '').trim(),
  ].slice(0, required);

  if (selected.some((v) => !v)) {
    if (required === 1) {
      return { ok: false, error: 'يجب اختيار رغبة قسم واحدة' };
    }
    if (required === 2) {
      return { ok: false, error: 'يجب اختيار رغبتين أقسام' };
    }
    return { ok: false, error: 'يجب اختيار ثلاث رغبات أقسام' };
  }

  if (new Set(selected).size < required) {
    if (required === 1) {
      return { ok: false, error: 'يجب اختيار رغبة قسم صالحة' };
    }
    if (required === 2) {
      return { ok: false, error: 'يجب أن تكون الرغبتان أقساماً مختلفة' };
    }
    return { ok: false, error: 'يجب أن تكون الرغبات الثلاث أقساماً مختلفة' };
  }

  const allowed = new Set(
    getAvailableDepartmentsForBranch(branch).map((d) => d.value)
  );
  if (selected.some((v) => !allowed.has(v))) {
    return { ok: false, error: 'أحد الأقسام المختارة غير متاح لهذا الفرع' };
  }

  return {
    ok: true,
    prefs: {
      first: selected[0] || '',
      second: selected[1] || '',
      third: selected[2] || '',
    },
  };
}
